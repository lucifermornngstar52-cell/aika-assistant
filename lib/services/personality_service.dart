    final prefs = await SharedPreferences.getInstance();
    final name = prefs.getString(_key) ?? 'jarvis';
    _current = AikaPersonality.values.firstWhere(
      (p) => p.name == name,
      orElse: () => AikaPersonality.jarvis,
    );
  }

